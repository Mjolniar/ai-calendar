"""Regenerates the XP-style icon set.

    python tools/xp-icons/generate.py

Writes app/src/main/java/com/example/aicalendar/xp/XpIcons.kt (Compose ImageVectors), the vector
drawables used by the launcher icon and notifications, and desktop/Xp/XpIcons.xaml (WPF
DrawingImages) for the Windows app. Edit icons.py, then re-run.

The Windows app's AppIcon.ico is a bitmap of the same artwork; the tests in desktop/tests draw
a fresh one (see desktop/README.md).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import icons  # noqa: E402
from iconlib import to_kotlin, to_vector_xml, to_xaml  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
if len(sys.argv) > 1:
    ROOT = os.path.abspath(sys.argv[1])
KOTLIN = os.path.join(ROOT, "app", "src", "main", "java", "com", "example", "aicalendar", "xp", "XpIcons.kt")
DRAWABLE = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
XAML = os.path.join(ROOT, "desktop", "Xp", "XpIcons.xaml")
NOTE = "Generated by tools/xp-icons/generate.py - edit icons.py instead."

HEADER = f"""// {NOTE}
package com.example.aicalendar.xp

import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.Brush
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** Original glossy icons drawn for the XP-style theme. Render with Image(), not Icon() (no tint). */
@Suppress("unused")
object XpIcons {{
"""

XAML_HEADER = f"""<!-- {NOTE} -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
"""

# drawable file name -> (icon spec, dp size)
DRAWABLES = {
    "ic_launcher_foreground": (icons.ART["launcher_fg"], 108),
    "ic_launcher_background": (icons.ART["launcher_bg"], 108),
    "ic_launcher_monochrome": (icons.ART["launcher_mono"], 108),
    "ic_notification": (icons.ART["notification_small"], 24),
    "xp_ic_info": (icons.ICONS["Info"], 24),
    "xp_ic_warning": (icons.ICONS["Warning"], 24),
}


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def main():
    body = "\n\n".join(to_kotlin(name, spec) for name, spec in icons.ICONS.items())
    kotlin = HEADER + body + "\n}\n"
    uses_evenodd = "PathFillType.EvenOdd" in kotlin
    if not uses_evenodd:
        kotlin = kotlin.replace("import androidx.compose.ui.graphics.PathFillType\n", "")
    write(KOTLIN, kotlin)
    for name, (spec, dp) in DRAWABLES.items():
        write(os.path.join(DRAWABLE, name + ".xml"), to_vector_xml(spec, dp=dp, header_comment=NOTE))
    if os.path.isdir(os.path.join(ROOT, "desktop")):
        images = [to_xaml("Icon." + name, spec) for name, spec in icons.ICONS.items()]
        images.append(to_xaml("Icon.AppLarge", icons.ART["desktop_app"]))
        write(XAML, XAML_HEADER + "\n".join(images) + "\n</ResourceDictionary>\n")


if __name__ == "__main__":
    main()
